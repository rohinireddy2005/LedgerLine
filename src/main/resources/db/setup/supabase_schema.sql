-- 1. Functions for Immutability & Financial Protections
CREATE OR REPLACE FUNCTION public.prevent_account_status_audit_modification()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'Account status audit records are immutable. UPDATE and DELETE are not allowed.';
END;
$$;

CREATE OR REPLACE FUNCTION public.prevent_ledger_modification()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'Ledger entries are immutable. UPDATE and DELETE are not allowed.';
END;
$$;

-- 2. Tables & Sequences

-- Table: users
CREATE TABLE IF NOT EXISTS public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) with time zone NOT NULL,
    email character varying(255) NOT NULL UNIQUE,
    full_name character varying(255) NOT NULL,
    password character varying(255) NOT NULL,
    role character varying(255) NOT NULL,
    CONSTRAINT users_role_check CHECK (role IN ('ACCOUNT_HOLDER', 'ADMIN', 'AUDITOR'))
);

-- Table: accounts
CREATE TABLE IF NOT EXISTS public.accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number character varying(20) NOT NULL UNIQUE,
    balance numeric(19,2) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    currency character varying(3) NOT NULL,
    status character varying(20) NOT NULL,
    owner_id bigint NOT NULL REFERENCES public.users(id),
    CONSTRAINT accounts_status_check CHECK (status IN ('ACTIVE', 'FROZEN', 'CLOSED')),
    CONSTRAINT chk_accounts_balance_nonnegative CHECK (balance >= 0)
);

-- Table: money_transactions
CREATE TABLE IF NOT EXISTS public.money_transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount numeric(19,2) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    idempotency_key character varying(255) NOT NULL,
    rejection_reason character varying(255),
    status character varying(20) NOT NULL,
    type character varying(20) NOT NULL,
    destination_account_id bigint REFERENCES public.accounts(id),
    initiator_id bigint NOT NULL REFERENCES public.users(id),
    source_account_id bigint REFERENCES public.accounts(id),
    CONSTRAINT money_transactions_status_check CHECK (status IN ('SUCCESS', 'REJECTED')),
    CONSTRAINT money_transactions_type_check CHECK (type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER')),
    CONSTRAINT chk_money_transactions_amount_positive CHECK (amount > 0),
    CONSTRAINT uk_money_transactions_initiator_idempotency UNIQUE (initiator_id, idempotency_key)
);

-- Table: ledger_entries
CREATE TABLE IF NOT EXISTS public.ledger_entries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount numeric(19,2) NOT NULL,
    balance_after numeric(19,2) NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    entry_type character varying(10) NOT NULL,
    account_id bigint NOT NULL REFERENCES public.accounts(id),
    transaction_id bigint NOT NULL REFERENCES public.money_transactions(id),
    CONSTRAINT ledger_entries_entry_type_check CHECK (entry_type IN ('CREDIT', 'DEBIT')),
    CONSTRAINT chk_ledger_entries_amount_positive CHECK (amount > 0),
    CONSTRAINT chk_ledger_entries_balance_nonnegative CHECK (balance_after >= 0)
);

-- Table: account_status_audits
CREATE TABLE IF NOT EXISTS public.account_status_audits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) with time zone NOT NULL,
    new_status character varying(20) NOT NULL,
    previous_status character varying(20) NOT NULL,
    reason character varying(500) NOT NULL,
    account_id bigint NOT NULL REFERENCES public.accounts(id),
    admin_id bigint NOT NULL REFERENCES public.users(id)
);

-- 3. Triggers for Immutability

DROP TRIGGER IF EXISTS trg_prevent_account_status_audit_modification ON public.account_status_audits;
CREATE TRIGGER trg_prevent_account_status_audit_modification
BEFORE UPDATE OR DELETE ON public.account_status_audits
FOR EACH ROW EXECUTE FUNCTION public.prevent_account_status_audit_modification();

DROP TRIGGER IF EXISTS trg_prevent_ledger_modification ON public.ledger_entries;
CREATE TRIGGER trg_prevent_ledger_modification
BEFORE UPDATE OR DELETE ON public.ledger_entries
FOR EACH ROW EXECUTE FUNCTION public.prevent_ledger_modification();
